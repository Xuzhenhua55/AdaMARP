def build_dialogue_context(log_data: Dict) -> str:
    main_char = log_data.get("roles", {}).get("main_character", {})
    main_name = main_char.get("name", "").strip()
    main_profile = main_char.get("profile", "").strip()
    main_motivation = main_char.get("motivation", "").strip()

    main_char_text = ""
    if main_name:
        main_char_text = f"{main_name}:{main_profile}"
        if main_motivation:
            main_char_text += f"\n{main_name}'s motivation:{main_motivation}"

    other_roles = log_data.get("roles", {}).get("other_characters", []) or []
    other_char_texts = []
    for role in other_roles:
        role_name = role.get("name", "").strip()
        role_profile = role.get("profile", "").strip()
        role_motivation = role.get("motivation", "").strip()
        if role_name:
            role_text = f"{role_name}:{role_profile}"
            if role_motivation:
                role_text += f"\n{role_name}'s motivation:{role_motivation}"
            other_char_texts.append(role_text)

    other_profiles = "\n".join(other_char_texts)
    dialogue_lines = []
    for msg in log_data.get("messages", []):
        role = msg.get("role") or msg.get("name") or "unknown_role"
        content = (msg.get("content") or "").strip()

        # Filter out scene_manager messages with "pick_speaker" in content
        # Keep all other scene_manager messages (init_scene, switch_scene, etc.)
        if role == "scene_manager" and "pick_speaker" in content:
            # print(f"Filtered out scene_manager message with 'pick_speaker' in content: {content}")
            continue

        dialogue_lines.append(f"{role}：{content}")
    dialogue_text = "\n".join(dialogue_lines)
    sections = [
        "===Main Character===",
        main_char_text,
        "===Information about the other Characters===",
        other_profiles,
        "===Dialogue History===",
        dialogue_text,
    ]
    return "\n".join([s for s in sections if s])

def build_messages(context_text: str) -> List:
    return [
        SystemMessage(content=ACTOR_RUBRIC),
        HumanMessage(content=context_text),
    ]

def read_log_records(log_path: str) -> List[Tuple[Dict, str]]:
    """Read a log file that may contain a single JSON object or JSONL with one object per line.

    Returns:
        List of tuples: (parsed_dict, original_line) for JSONL, or (parsed_dict, None) for JSON.
    """
    records: List[Tuple[Dict, str]] = []

    # Try JSONL first (most common case - each line is a session)
    with open(log_path, "r", encoding="utf-8") as f:
        lines = f.readlines()

    # Try parsing as JSONL (each line is a JSON object)
    jsonl_success = False
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
            if isinstance(obj, dict):
                records.append((obj, line))
                jsonl_success = True
        except json.JSONDecodeError:
            continue

    # If JSONL parsing succeeded, return results
    if jsonl_success:
        return records

    # Fallback to single JSON object (for backward compatibility)
    try:
        with open(log_path, "r", encoding="utf-8") as f:
            loaded = json.load(f)
        if isinstance(loaded, dict):
            return [(loaded, None)]
        if isinstance(loaded, list):
            return [(item, None) for item in loaded if isinstance(item, dict)]
    except json.JSONDecodeError:
        pass

    if not records:
        raise ValueError(f"Could not parse any JSON objects from {log_path}")
    return records

def extract_json_from_markdown(content: str) -> str:
    """Extract JSON content from markdown code blocks or plain text.

    Handles cases where LLM wraps JSON in ```json ... ``` blocks.
    Improved to handle more edge cases including incomplete JSON.
    """
    content = content.strip()

    # Try to extract JSON from markdown code blocks
    # Pattern: ```json ... ``` or ``` ... ```
    # Match ```json ... ``` or ``` ... ```
    json_block_pattern = r'```(?:json)?\s*\n?(.*?)\n?```'
    match = re.search(json_block_pattern, content, re.DOTALL)
    if match:
        return match.group(1).strip()

    # If no code block found, try to find JSON object boundaries
    # Look for first { and try to extract from there
    first_brace = content.find('{')
    if first_brace >= 0:
        # Try to find the matching closing brace
        brace_count = 0
        in_string = False
        escape_next = False
        for i in range(first_brace, len(content)):
            char = content[i]
            if escape_next:
                escape_next = False
                continue
            if char == '\\':
                escape_next = True
                continue
            if char == '"' and not escape_next:
                in_string = not in_string
                continue
            if not in_string:
                if char == '{':
                    brace_count += 1
                elif char == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        return content[first_brace:i+1]
        # If no closing brace found, return from first brace to end (might be truncated)
        return content[first_brace:]

    # If no JSON structure found, return original content
    return content

def evaluate_one(model, log_data: Dict) -> Tuple[Dict, str, Dict]:
    context_text = build_dialogue_context(log_data)
    messages = build_messages(context_text)
    # ChatModelWrapper.invoke() expects a state dict with "messages" key
    state = {"messages": messages}
    response = model.invoke(state)
    content = getattr(response, "content", "") or ""
    parsed = {}
    try:
        # First try parsing as-is
        parsed = json.loads(content)
    except json.JSONDecodeError:
        # Try extracting JSON from markdown code blocks
        try:
            cleaned_content = extract_json_from_markdown(content)
            parsed = json.loads(cleaned_content)
        except json.JSONDecodeError:
            parsed = {"parse_error": "LLM response was not valid JSON", "raw": content}
    # Extract token usage information
    # ChatModelWrapper.invoke() returns an object with .usage attribute
    usage_info = {}
    if hasattr(response, "usage") and response.usage:
        usage_info = response.usage
        # Convert to dict if it's an object
        if not isinstance(usage_info, dict):
            usage_info = {
                "prompt_tokens": getattr(usage_info, "prompt_tokens", 0),
                "completion_tokens": getattr(usage_info, "completion_tokens", 0),
                "total_tokens": getattr(usage_info, "total_tokens", 0),
            }
    elif hasattr(response, "response_metadata") and response.response_metadata:
        usage_info = response.response_metadata.get("token_usage", {})
    return parsed, content, usage_info

def extract_score(parsed: Dict, path: List[str]) -> float | None:
    """Extract score from nested structure using a path list.

    Args:
        parsed: The parsed JSON response
        path: List of keys to navigate (e.g., ["character_consistency", "internal_coherence"])

    Returns:
        The score value as float, or None if not found.
    """
    try:
        current = parsed
        for key in path:
            if not isinstance(current, dict):
                return None
            current = current.get(key)
            if current is None:
                return None

        # At the end of the path, we expect a dict with a "score" key
        if isinstance(current, dict):
            val = current.get("score")
            if isinstance(val, (int, float)):
                return float(val)
    except Exception:
        return None
    return None

def validate_scores(parsed: Dict) -> Tuple[bool, List[str]]:
    """Validate that all required scores are successfully parsed according to the nested schema.

    Returns:
        Tuple of (is_valid, missing_paths) where missing_paths is a list of paths that are missing.
    """
    if "parse_error" in parsed:
        return False, ["parse_error"]

    # Define the schema of required scores based on ACTOR_RUBRIC
    # List of paths to check
    required_paths = [
        ["character_consistency", "internal_coherence"],
        ["character_consistency", "speaking_style_fidelity"],
        ["character_consistency", "language_fluency"],
        ["character_consistency", "identity_fidelity"],
        ["character_consistency", "motivation_stability"],
        ["environmental_grounding", "environmental_awareness"],
        ["environmental_grounding", "environmental_utilization"],
        ["interpersonal_interaction", "contextual_responsiveness"],
        ["interpersonal_interaction", "relationship_awareness"],
        ["narrative_progression", "narrative_attractiveness"],
        ["narrative_progression", "stability_over_time"],
        ["instruction_compliance"] # This one is at the top level in the rubric example
    ]

    missing_paths = []
    for path in required_paths:
        score = extract_score(parsed, path)
        if score is None:
            missing_paths.append(" -> ".join(path))

    return len(missing_paths) == 0, missing_paths

def load_existing_records(output_path: str) -> Dict[str, Dict]:
    """Load all records from the output file if it exists, indexed by UUID."""
    existing_records = {}
    if os.path.exists(output_path):
        try:
            with open(output_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        record = json.loads(line)
                        if "uuid" in record and record["uuid"]:
                            existing_records[record["uuid"]] = record
                    except json.JSONDecodeError:
                        continue
        except Exception:
            pass
    return existing_records

# Thread-safe file writing lock
_file_write_lock = threading.Lock()
def append_jsonl(path: str, record: Dict) -> None:
    """Thread-safe JSONL append operation."""
    dir_path = os.path.dirname(path)
    if dir_path:  # Only create directory if path has a directory component
        os.makedirs(dir_path, exist_ok=True)
    with _file_write_lock:
        with open(path, "a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")

def process_one_record(
    log_obj: Dict,
    judge,
    args,
    existing_records_by_uuid: Dict[str, Dict],
) -> Tuple[Dict | None, Dict, Dict, bool]:
    """Process a single log record for evaluation.

    Returns:
        Tuple of (record, parsed_scores, token_usage, is_new_record)
        Returns (None, {}, {}, False) if the record should be skipped.
        is_new_record: True if this is a newly evaluated record, False if it already existed.
    """
    uuid_value = log_obj.get("uuid")

    # Check UUID to avoid duplicate evaluations
    if uuid_value and uuid_value in existing_records_by_uuid:
        # UUID already exists in output file, skip evaluation and use existing record
        record = existing_records_by_uuid[uuid_value]
        existing_eval = record.get("evaluation", {})
        parsed = existing_eval.get("scores", {})

        # Validate scores - skip if parsing failed
        is_valid, missing_paths = validate_scores(parsed)
        if not is_valid:
            uuid_str = uuid_value or "unknown"
            raw_response = existing_eval.get("raw_response", "")
            print(f"Skipping record with UUID {uuid_str}: score parsing failed", file=sys.stderr)
            print(f"Raw output for UUID {uuid_str}:", file=sys.stderr)
            print(f"{raw_response}", file=sys.stderr)
            print(f"Parsed content: {json.dumps(parsed, ensure_ascii=False, indent=2)}", file=sys.stderr)
            return None, {}, {}, False

        # Extract token usage from existing evaluation if available
        usage_info = existing_eval.get("token_usage", {})
        if usage_info:
            prompt_tokens = usage_info.get("prompt_tokens", 0) or usage_info.get("input_tokens", 0) or 0
            completion_tokens = usage_info.get("completion_tokens", 0) or usage_info.get("output_tokens", 0) or 0
            total_tokens = usage_info.get("total_tokens", 0) or (prompt_tokens + completion_tokens)
            usage_info = {
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": total_tokens,
            }
        else:
            usage_info = {}

        return record, parsed, usage_info, False  # False = already exists, don't write again

    # Need to evaluate (with retries)
    uuid_str = log_obj.get("uuid", "unknown")
    max_attempts = args.max_retries + 1  # +1 for the initial attempt
    parsed, raw, usage_info = None, "", {}

    for attempt in range(max_attempts):
        try:
            parsed, raw, usage_info = evaluate_one(judge, log_obj)
            is_valid, missing_paths = validate_scores(parsed)
            if is_valid:
                break  # Success, exit retry loop
            else:
                if attempt < max_attempts - 1:
                    print(f"Attempt {attempt + 1}/{max_attempts} failed for UUID {uuid_str}: missing paths {', '.join(missing_paths)}, retrying...", file=sys.stderr)
                    continue
                else:
                    print(f"Skipping record with UUID {uuid_str}: score parsing failed after {max_attempts} attempts", file=sys.stderr)
                    print(f"Missing paths: {', '.join(missing_paths)}", file=sys.stderr)
                    print(f"Raw output for UUID {uuid_str}:\n{raw}", file=sys.stderr)
                    print(f"Parsed content: {json.dumps(parsed, ensure_ascii=False, indent=2)[:2000]}", file=sys.stderr)
                    return None, {}, {}, False
        except Exception as e:
            if attempt < max_attempts - 1:
                print(f"Attempt {attempt + 1}/{max_attempts} raised exception for UUID {uuid_str}: {e}, retrying...", file=sys.stderr)
                continue
            else:
                print(f"Skipping record with UUID {uuid_str}: evaluation raised exception after {max_attempts} attempts: {e}", file=sys.stderr)
                return None, {}, {}, False

    # Final validation (should have passed if we got here, but double-check)
    is_valid, missing_paths = validate_scores(parsed)
    if not is_valid:
        print(f"Skipping record with UUID {uuid_str}: score parsing failed after validation", file=sys.stderr)
        print(f"Missing paths: {', '.join(missing_paths)}", file=sys.stderr)
        return None, {}, {}, False

    # Build output record: preserve original data and add evaluation results
    record = log_obj.copy()

    # Add evaluation results
    record["evaluation"] = {
        "judge_model": args.model,
        "scores": parsed,
        "raw_response": raw,
    }

    # Add token usage to evaluation if available
    if usage_info:
        record["evaluation"]["token_usage"] = usage_info

    return record, parsed, usage_info, True  # True = new record, should write to file

def main():
    args = parse_args()
    log_paths = expand_log_paths(args.logs)
    if not log_paths:
        raise FileNotFoundError("No log files found for the given --logs patterns.")

    config = load_config(args.config)
    api_key, base_url = resolve_model_credentials(args.model, config, args.api_key, args.base_url)

    judge = create_chat_model(
        args.model,
        generation_config={
            "temperature": args.temperature,
            "max_new_tokens": 10240,
        },
        api_key=api_key,
        base_url=base_url,
    )

    # Metrics definition for statistics
    # Maps a flat key (for display) to the path in the JSON structure
    metric_paths = {
        "CC_internal_coherence": ["character_consistency", "internal_coherence"],
        "CC_speaking_style": ["character_consistency", "speaking_style_fidelity"],
        "CC_language_fluency": ["character_consistency", "language_fluency"],
        "CC_identity_fidelity": ["character_consistency", "identity_fidelity"],
        "CC_motivation_stability": ["character_consistency", "motivation_stability"],
        "EG_awareness": ["environmental_grounding", "environmental_awareness"],
        "EG_utilization": ["environmental_grounding", "environmental_utilization"],
        "II_contextual_responsiveness": ["interpersonal_interaction", "contextual_responsiveness"],
        "II_relationship_awareness": ["interpersonal_interaction", "relationship_awareness"],
        "NP_narrative_attractiveness": ["narrative_progression", "narrative_attractiveness"],
        "NP_stability_over_time": ["narrative_progression", "stability_over_time"],
        "Instruction_Compliance": ["instruction_compliance"]
    }

    # Initialize score accumulators
    all_scores = {k: [] for k in metric_paths.keys()}

    total_token_usage = {
        "prompt_tokens": 0,
        "completion_tokens": 0,
        "total_tokens": 0,
    }
    stats_lock = threading.Lock()

    # Load existing records from output file to avoid duplicate evaluations
    existing_records_by_uuid = {}
    if args.output:
        existing_records_by_uuid = load_existing_records(args.output)

    # Collect records
    all_records: List[Tuple[Dict, str]] = []
    for path in log_paths:
        records = read_log_records(path)
        all_records.extend(records)
        if args.limit is not None and len(all_records) >= args.limit:
            break

    if args.limit is not None:
        all_records = all_records[:args.limit]

    # Process records concurrently or sequentially
    if args.concurrency > 1:
        # Concurrent processing
        with ThreadPoolExecutor(max_workers=args.concurrency) as executor:
            # Submit all tasks
            future_to_record = {
                executor.submit(
                    process_one_record,
                    log_obj,
                    judge,
                    args,
                    existing_records_by_uuid,
                ): (log_obj, original_line)
                for log_obj, original_line in all_records
            }

            # Process completed tasks
            for future in as_completed(future_to_record):
                log_obj, original_line = future_to_record[future]
                try:
                    record, parsed, usage_info, is_new_record = future.result()

                    # Skip if record was None (validation failed)
                    if record is None:
                        continue

                    # Print result
                    # print(json.dumps(record, ensure_ascii=False, indent=2))

                    # Write to output file only if this is a new record (thread-safe)
                    if args.output and is_new_record:
                        append_jsonl(args.output, record)

                    # Accumulate statistics (thread-safe)
                    with stats_lock:
                        # Accumulate scores
                        for metric_name, path in metric_paths.items():
                            val = extract_score(parsed, path)
                            if val is not None:
                                all_scores[metric_name].append(val)

                        # Accumulate token usage
                        if usage_info:
                            total_token_usage["prompt_tokens"] += usage_info.get("prompt_tokens", 0)
                            total_token_usage["completion_tokens"] += usage_info.get("completion_tokens", 0)
                            total_token_usage["total_tokens"] += usage_info.get("total_tokens", 0)

                except Exception as exc:
                    uuid_str = log_obj.get("uuid", "unknown")
                    print(f"Record with UUID {uuid_str} generated an exception: {exc}", file=sys.stderr)
    else:
        # Sequential processing (original behavior)
        for log_obj, original_line in all_records:
            record, parsed, usage_info, is_new_record = process_one_record(
                log_obj,
                judge,
                args,
                existing_records_by_uuid,
            )

            # Skip if record was None (validation failed)
            if record is None:
                continue

            # Print result
            # print(json.dumps(record, ensure_ascii=False, indent=2))

            # Write to output file only if this is a new record
            if args.output and is_new_record:
                append_jsonl(args.output, record)

            # Accumulate statistics
            for metric_name, path in metric_paths.items():
                val = extract_score(parsed, path)
                if val is not None:
                    all_scores[metric_name].append(val)

            # Accumulate token usage
            if usage_info:
                total_token_usage["prompt_tokens"] += usage_info.get("prompt_tokens", 0)
                total_token_usage["completion_tokens"] += usage_info.get("completion_tokens", 0)
                total_token_usage["total_tokens"] += usage_info.get("total_tokens", 0)

    # Calculate and print summary
    avg = {}
    sample_count = 0
    for key, vals in all_scores.items():
        if vals:
            avg[key] = sum(vals) / len(vals)
            sample_count = max(sample_count, len(vals))

    summary = {}
    if avg:
        summary["average_scores"] = avg
        summary["sample_count"] = sample_count

    if total_token_usage["total_tokens"] > 0:
        summary["total_token_usage"] = total_token_usage

    if summary:
        print(json.dumps(summary, ensure_ascii=False, indent=2))

if __name__ == "__main__":
    main()
